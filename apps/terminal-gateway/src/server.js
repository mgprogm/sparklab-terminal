// Canonical parse/format lives in packages/shared-types/src/terminal.ts
// (parseSessionRef / formatSessionRef / LOCAL_SERVER_ID). The gateway is plain
// dependency-free JS and CANNOT import that module at runtime (same reason it
// duplicates AGENT_NAMED_KEYS), so we mirror the exact split/join here — KEEP
// THE TWO IN SYNC.
const LOCAL_SERVER_ID = "local";

// Split on the FIRST "/": before => serverId, after => tmux name. No "/" means
// a bare tmux name (old bookmark / single-server client) => serverId "local".
function parseSessionRef(ref) {
  const slash = ref.indexOf("/");
  if (slash < 0) return { serverId: LOCAL_SERVER_ID, tmuxName: ref };
  return {
    serverId: ref.slice(0, slash) || LOCAL_SERVER_ID,
    tmuxName: ref.slice(slash + 1),
  };
}

// Always emit the canonical qualified form (even for "local") so the target
// host is never implicit anywhere on the wire.
function formatSessionRef(serverId, tmuxName) {
  return `${serverId || LOCAL_SERVER_ID}/${tmuxName}`;
}

// One control socket per server so every control exec AND the WS attach reuse a
// single TCP+auth handshake (ControlMaster). Kept short to stay under the
// ~104-char unix-socket path limit.
const SSH_CONTROL_DIR = path.join(os.tmpdir(), "gw-ssh-cm");
try {
  fs.mkdirSync(SSH_CONTROL_DIR, { recursive: true, mode: 0o700 });
} catch {}

// Password auth (opt-in per server) uses OpenSSH's askpass helper rather than a
// prompt: SSH_ASKPASS_REQUIRE=force (OpenSSH >= 8.4) makes ssh read the password
// from this helper even without a controlling terminal AND even when node-pty
// gives the attach a pty — so both exec seams work non-interactively. The helper
// echoes $GW_SSH_PASSWORD, which we pass via the child env (NOT argv), so the
// secret never appears in `ps`. Key-based servers never touch any of this.
const SSH_ASKPASS_PATH = path.join(SSH_CONTROL_DIR, "askpass.sh");
try {
  fs.writeFileSync(
    SSH_ASKPASS_PATH,
    "#!/bin/sh\nprintf '%s\\n' \"$GW_SSH_PASSWORD\"\n",
    { mode: 0o700 },
  );
} catch {}

function sshHost(server) {
  return server.user ? `${server.user}@${server.host}` : server.host;
}

// Extra child-process env for a server. For password auth, wire the askpass
// helper + force it + pass the secret by env (never argv). Empty for local and
// key-based servers, so their spawn env is unchanged.
function sshEnvFor(server) {
  if (server && server.type === "ssh" && server.password) {
    return {
      SSH_ASKPASS: SSH_ASKPASS_PATH,
      SSH_ASKPASS_REQUIRE: "force",
      GW_SSH_PASSWORD: server.password,
    };
  }
  return {};
}

// Merge process.env with the server's extra ssh env. Only allocates a new object
// when there's something to add.
function childEnvFor(server) {
  const extra = sshEnvFor(server);
  return Object.keys(extra).length ? { ...process.env, ...extra } : process.env;
}

// Shared ssh options for BOTH control execs and the reachability probe. Two
// modes: key-based (BatchMode=yes => ssh never prompts) or password (askpass;
// pubkey disabled so we go straight to the password, single attempt).
function sshOptsFor(server) {
  const usePassword = !!(server && server.password);
  const opts = [
    "-o",
    usePassword ? "BatchMode=no" : "BatchMode=yes",
    "-o",
    "StrictHostKeyChecking=accept-new",
    "-o",
    "ConnectTimeout=8",
    "-o",
    "ServerAliveInterval=15",
    "-o",
    "ControlMaster=auto",
    "-o",
    `ControlPath=${path.join(SSH_CONTROL_DIR, "cm-%r@%h:%p")}`,
    "-o",
    "ControlPersist=60s",
  ];
  if (usePassword) {
    // Go straight to password auth in one attempt; the control socket then
    // carries every later exec/attach so the password is only used on connect.
    opts.push(
      "-o",
      "PreferredAuthentications=password",
      "-o",
      "PubkeyAuthentication=no",
      "-o",
      "NumberOfPasswordPrompts=1",
    );
  }
  if (server.port) opts.push("-p", String(server.port));
  if (!usePassword && server.identityFile) {
    opts.push("-i", server.identityFile, "-o", "IdentitiesOnly=yes");
  }
  return opts;
}

// POSIX single-quote an argument for the REMOTE shell. Wrap in single quotes
// and escape any embedded single quote as '\''. Only needed on the ssh path.
function shellQuote(arg) {
  return `'${String(arg).replace(/'/g, "'\\''")}'`;
}

// THE EXEC SEAM. Returns argv for execFile/ptySpawn running `tmux <tmuxArgs>`
// either locally or over ssh. For type:"local" it returns the bare tmux argv —
// ZERO behavior change for the single-server path. `tty:true` forces ssh to
// allocate a pty (the WS-attach seam needs `ssh -tt … tmux attach-session`).
// `server.tmuxCommand` (file-only config, e.g. ["tmux","-L","sock"]) overrides
// the tmux invocation so a test/advanced setup can target a separate socket.
//
// Local vs remote quoting: locally we execFile tmux directly (no shell), so each
// argv element is already one literal argument. Over ssh, the remote sshd runs
// the command through a shell that RE-SPLITS on whitespace and interprets
// metacharacters — so a `-F "#{a}\t#{b}"` format (spaces/tabs), a `send-keys`
// text arg, or a cwd path with spaces would break. We therefore shell-quote
// every token into a single remote command string so the remote tmux receives
// the exact same argv it would locally.
function serverExecArgv(server, tmuxArgs, { tty = false } = {}) {
  const tmuxCmd =
    Array.isArray(server && server.tmuxCommand) && server.tmuxCommand.length
      ? server.tmuxCommand
      : ["tmux"];
  if (!server || server.type === "local") {
    return [...tmuxCmd, ...tmuxArgs];
  }
  const argv = ["ssh"];
  if (tty) argv.push("-tt");
  const remoteCmd = [...tmuxCmd, ...tmuxArgs].map(shellQuote).join(" ");
  argv.push(...sshOptsFor(server), sshHost(server), remoteCmd);
  return argv;
}

// Control-seam exec: run tmux on `server`, await stdout/stderr.
async function serverExec(server, tmuxArgs) {
  const argv = serverExecArgv(server, tmuxArgs);
  return execFileAsync(argv[0], argv.slice(1), { env: childEnvFor(server) });
}

// Control-seam exec with `input` piped to stdin (used by `load-buffer -`).
// promisified execFile exposes the underlying ChildProcess as `.child`; the
// input flows through the ssh child exactly as it did through the tmux child.
async function serverExecStdin(server, tmuxArgs, input) {
  const argv = serverExecArgv(server, tmuxArgs);
  const promise = execFileAsync(argv[0], argv.slice(1), {
    env: childEnvFor(server),
  });
  promise.child.stdin.end(input);
  return promise;
}

// ---------------------------------------------------------------------------
// Non-tmux exec seam: serverCmdArgv / serverCmd / serverCmdStdin
// ---------------------------------------------------------------------------
// Identical to serverExecArgv/serverExec/serverExecStdin but WITHOUT the tmux
// prefix — they run an ARBITRARY argv (find/head/cat/mkdir/mv/rm/tee) locally
// or over ssh. Used by the File Explorer fs/* routes. Same quoting contract:
// locally we execFile argv[0] directly (no shell, each element one literal
// argument); over ssh the remote sshd re-splits on whitespace, so every token
// is shellQuote'd into one remote command string. Reuse childEnvFor so the
// password-auth askpass env is present. Callers MUST pass paths as a single
// argv element and terminate options with `--`; never concatenate a path into
// a command string.

// Default child maxBuffer: the fs listing (up to ~5000 entries) and a 256 KB
// read must fit. execFile's default is only 1 MB.
const FS_CMD_MAX_BUFFER = 16 * 1024 * 1024;
const FS_CMD_TIMEOUT_MS = 15_000;

function serverCmdArgv(server, argv, { tty = false } = {}) {
  if (!server || server.type === "local") {
    return argv;
  }
  const ssh = ["ssh"];
  if (tty) ssh.push("-tt");
  const remoteCmd = argv.map(shellQuote).join(" ");
  ssh.push(...sshOptsFor(server), sshHost(server), remoteCmd);
  return ssh;
}

// Run an arbitrary argv on `server`, await stdout/stderr. Mirrors serverExec.
async function serverCmd(server, argv, opts = {}) {
  const a = serverCmdArgv(server, argv);
  return execFileAsync(a[0], a.slice(1), {
    env: childEnvFor(server),
    timeout: FS_CMD_TIMEOUT_MS,
    maxBuffer: FS_CMD_MAX_BUFFER,
    ...opts,
  });
}

// Run an arbitrary argv on `server` with `input` piped to stdin. Mirrors
// serverExecStdin; used by fs/upload (`tee -- <dest>`). `input` is a Buffer or
// string already buffered under the route-local upload cap.
async function serverCmdStdin(server, argv, input, opts = {}) {
  const a = serverCmdArgv(server, argv);
  const promise = execFileAsync(a[0], a.slice(1), {
    env: childEnvFor(server),
    timeout: FS_CMD_TIMEOUT_MS,
    maxBuffer: FS_CMD_MAX_BUFFER,
    ...opts,
  });
  promise.child.stdin.end(input);
  return promise;
}

// ---- Cached reachability probe (`ssh <host> true`) ----
// The 3 s session poll and GET /api/servers must not fire a fresh ssh probe per
// server per tick, so results are cached with a short TTL. "local" is always
// "ok" (no ssh). "unreachable" means "couldn't ask" — never "dead".
const REACHABILITY_TTL_MS = 12_000;
const reachabilityCache = new Map(); // serverId -> { reachability, lastProbeAt, at }

async function probeServer(server, { force = false } = {}) {
  if (!server || server.type === "local") {
    return { reachability: "ok", lastProbeAt: null };
  }
  const cached = reachabilityCache.get(server.id);
  if (!force && cached && Date.now() - cached.at < REACHABILITY_TTL_MS) {
    return {
      reachability: cached.reachability,
      lastProbeAt: cached.lastProbeAt,
    };
  }
  let reachability = "unreachable";
  let error;
  try {
    const argv = ["ssh", ...sshOptsFor(server), sshHost(server), "true"];
    await execFileAsync(argv[0], argv.slice(1), {
      timeout: 10_000,
      env: childEnvFor(server),
    });
    reachability = "ok";
  } catch (err) {
    error = String(err.stderr || err.message || "")
      .trim()
      .slice(0, 300);
  }
  const lastProbeAt = Date.now();
  reachabilityCache.set(server.id, {
    reachability,
    lastProbeAt,
    at: lastProbeAt,
  });
  return { reachability, lastProbeAt, error };
}

async function sessionExists(server, name) {
  if (!ID_RE.test(name)) return false;
  try {
    await serverExec(server, ["has-session", "-t", name]);
    return true;
  } catch {
    return false;
  }
}

// One-line shell hook (bash + zsh) installed at session-create time so a job's
// exit code is captured for "job finished" notifications. It writes $? to a
// SESSION-scoped tmux user option `@web_last_exit` on every prompt; the poll
// loop reads it via `#{@web_last_exit}` in list-sessions (verified to resolve).
// Notes: captures $? FIRST (before any clobber); a `__SL_HOOK` sentinel guards
// against double-install; the tmux call is quiet + non-fatal (`-q`, 2>/dev/null)
// so a non-tmux/plain shell is unaffected. bash/zsh + gateway-created sessions
// only — other shells / pre-existing sessions simply never set it (exitCode is
// then omitted from the payload; the backward-compat contract).
const EXIT_HOOK =
  'if [ -z "$__SL_HOOK" ]; then __SL_HOOK=1; ' +
  'if [ -n "$ZSH_VERSION" ]; then __sl(){ local ec=$?; tmux set-option -q @web_last_exit "$ec" 2>/dev/null; }; precmd_functions+=(__sl); ' +
  'elif [ -n "$BASH_VERSION" ]; then PROMPT_COMMAND=\'__ec=$?; tmux set-option -q @web_last_exit "$__ec" 2>/dev/null\'"${PROMPT_COMMAND:+;$PROMPT_COMMAND}"; fi; fi';

// Create + configure a new session on `server`. This is the only path that
// spawns a tmux session; attach never creates. Options mirror Phase 1.
async function createSession(server, id, cwd) {
  const args = ["new-session", "-d", "-s", id];
  if (cwd) args.push("-c", cwd);
  await serverExec(server, args);
  await serverExec(server, [
    "set-option",
    "-t",
    id,
    "history-limit",
    "50000",
  ]).catch((e) => console.warn(`[tmux] history-limit failed: ${e.message}`));
  // status off is a server-global nicety; scope with -g and swallow errors.
  await serverExec(server, ["set-option", "-g", "status", "off"]).catch((e) =>
    console.warn(`[tmux] status off failed: ${e.message}`),
  );
  // Prefer the most recently active client's size when multiple viewers attach.
  await serverExec(server, [
    "set-option",
    "-t",
    id,
    "window-size",
    "latest",
  ]).catch(() => {});
  await serverExec(server, [
    "set-option",
    "-t",
    id,
    "aggressive-resize",
    "on",
  ]).catch(() => {});
  // Install the exit-code capture hook (bash/zsh). Typed literally (-l) so its
  // quotes/`$` survive, then Enter to run it, then `clear` to hide it. Quiet +
  // non-fatal — a session still works if this is lost.
  try {
    await serverExec(server, ["send-keys", "-t", id, "-l", EXIT_HOOK]);
    await serverExec(server, ["send-keys", "-t", id, "Enter"]);
    await serverExec(server, ["send-keys", "-t", id, "-l", "clear"]);
    await serverExec(server, ["send-keys", "-t", id, "Enter"]);
  } catch (e) {
    console.warn(`[tmux] exit-hook install failed: ${e.message}`);
  }
  console.log(`[tmux] created session "${id}" on server "${server.id}"`);
}

// List only web- prefixed sessions across ALL registered servers, joined with
// metadata. Per-server error-isolated: one dead host must NEVER fail the whole
// list. A reachable server contributes live `tmux ls` rows (reachable:true); an
// UNREACHABLE server contributes last-known rows reconstructed from the sidecar
// (reachable:false) — never omitted, never pruned.
async function listSessions() {
  const servers = registry.list();
  const meta = metadata.list();
  const sessions = [];
  const liveIds = [];
  const reachableServerIds = new Set();

  await Promise.all(
    servers.map(async (server) => {
      let out = "";
      let ok = false;
      try {
        const res = await serverExec(server, [
          "list-sessions",
          "-F",
          "#{session_name}\t#{session_created}\t#{pane_current_command}\t#{session_attached}\t#{session_activity}\t#{@web_last_exit}",
        ]);
        out = res.stdout;
        ok = true;
      } catch (err) {
        // Local: "no server running" is normal => reachable with zero sessions.
        // Remote tmux can also report "no server running" while SSH itself is
        // healthy (for example, after a host reboot). Probe SSH separately so
        // that case becomes reachable with zero live sessions, while a genuine
        // host outage still reconstructs last-known reachable:false rows.
        if (server.type === "local") {
          ok = true;
          out = "";
        } else {
          const probe = await probeServer(server, { force: true });
          if (probe.reachability === "ok") {
            ok = true;
            out = "";
          } else {
            ok = false;
            console.warn(
              `[api] list on server "${server.id}" failed: ${err.message}`,
            );
          }
        }
      }
      if (!ok) return; // unreachable: reconstructed from the sidecar below
      reachableServerIds.add(server.id);
      for (const line of out.split("\n")) {
        if (!line.trim()) continue;
        const [name, created, currentCommand, attached, activity, lastExit] =
          line.split("\t");
        if (!name || !name.startsWith(PREFIX)) continue;
        // Exit code from the shell hook's @web_last_exit (bash/zsh, gateway-
        // created sessions). Empty/unset/non-numeric => null (omitted downstream).
        const exitCode = /^-?\d+$/.test((lastExit || "").trim())
          ? Number(lastExit.trim())
          : null;
        const qid = formatSessionRef(server.id, name);
        liveIds.push(qid);
        const m = meta[qid] || {};
        sessions.push({
          id: qid,
          name: m.name || name,
          createdAt: m.createdAt || (created ? Number(created) * 1000 : null),
          tags: m.tags || [],
          currentCommand: currentCommand || "",
          attached: Number(attached) > 0,
          attachedClients: Number(attached) || 0,
          lastActivity: activity ? Number(activity) : null,
          org: m.org ?? null,
          project: m.project ?? null,
          muted: m.muted ?? false,
          exitCode,
          serverId: server.id,
          reachable: true,
          alive: true,
        });
      }
    }),
  );

  // Reconstruct last-known rows for every registered server that did NOT
  // respond this tick, from the metadata sidecar. reachable:false, and the
  // unknowable fields are nulled/emptied (the FE greys off `reachable`).
  for (const server of servers) {
    if (reachableServerIds.has(server.id)) continue;
    for (const [qid, m] of Object.entries(meta)) {
      const { serverId, tmuxName } = parseSessionRef(qid);
      if (serverId !== server.id) continue;
      if (!tmuxName.startsWith(PREFIX)) continue;
      sessions.push({
        id: qid,
        name: m.name || tmuxName,
        createdAt: m.createdAt || null,
        tags: m.tags || [],
        currentCommand: "",
        attached: false,
        attachedClients: 0,
        lastActivity: null,
        org: m.org ?? null,
        project: m.project ?? null,
        muted: m.muted ?? false,
        serverId: server.id,
        reachable: false,
      });
    }
  }

  // Synthesize rows for sessions whose server responded fine this tick but
  // whose tmux session was NOT in the live output (e.g. host rebooted, or the
  // tmux session was killed outside the gateway). These are "dead"
  // placeholders: reachable:true (we CAN reach the server), alive:false (the
  // specific session is gone from tmux). They persist until the user
  // explicitly deletes them — no TTL, no auto-expiry (intentional).
  //
  // DELIBERATE BEHAVIOR REVERSAL: metadata for such sessions used to be pruned
  // here via metadata.pruneToExisting(), which is now removed so dead sessions
  // stay visible in the sidebar instead of vanishing without a trace.
  const liveSet = new Set(liveIds);
  for (const [qid, m] of Object.entries(meta)) {
    const sid = parseSessionRef(qid).serverId;
    if (!reachableServerIds.has(sid)) continue; // unreachable server: handled above
    if (liveSet.has(qid)) continue; // live: already in sessions[]
    const tmux = parseSessionRef(qid).tmuxName;
    if (!tmux.startsWith(PREFIX)) continue;
    sessions.push({
      id: qid,
      name: m.name || tmux,
      createdAt: m.createdAt || null,
      tags: m.tags || [],
      currentCommand: "",
      attached: false,
      attachedClients: 0,
      lastActivity: null,
      org: m.org ?? null,
      project: m.project ?? null,
      muted: m.muted ?? false,
      serverId: sid,
      reachable: true,
      alive: false,
    });
  }
  // metadata.pruneToExisting() is deliberately NOT called here anymore. Dead
  // session metadata persists until the user explicitly deletes via
  // DELETE /api/sessions/:id.
  return sessions;
}

// ---------------------------------------------------------------------------
// Push "job finished" poll loop
// ---------------------------------------------------------------------------
//
// The ONLY new always-on architectural change, and it is fully inert unless
// there is ≥1 push subscription AND VAPID is configured: the loop is started
// when the first subscription arrives and stopped when the last leaves, so
// zero subscriptions => zero cost, zero behavior change (identical single-
// server / remote-SSH profile to before this feature).
//
// Signal: a session's `pane_current_command` (already returned per-session by
// listSessions()) transitioning from a real non-shell command to a shell. NO
// screen-diffing — list-sessions gives currentCommand cheaply in one call.
//
// Baseline: the FIRST tick after a (re)start records every session's current
// command and notifies nothing — otherwise every already-running job would
// "finish" on gateway restart and spam. Per-session last-known state is
// in-memory/transient (jobs survive; notifications are best-effort).

// Login shells arrive as "bash"/"zsh" or, for a login shell, "-bash"/"-zsh".
// Mirrors the SHELLS set the agent-service uses (apps/agent-service/src/tools.ts).
const SHELLS = new Set(["bash", "zsh", "fish", "sh", "dash"]);
// Env-overridable so tests can poll at ~200ms instead of sleeping 30s.
const PUSH_POLL_INTERVAL_MS = Number(process.env.PUSH_POLL_INTERVAL_MS) || 4000;

let pushPollTimer = null;
// qid -> { cmd, startedAt: number|null, notifiedRunning: boolean }. startedAt is
// the epoch-ms when the current job began (shell->non-shell); null when unknown
// (job already running at baseline). notifiedRunning guards the one-time
// "still running after threshold" alert.
let pushState = new Map();
let pushBaselinePending = true;

function isShellCommand(cmd) {
  if (!cmd) return false; // "" is UNKNOWN, never a shell, never a trigger
  const base = cmd.startsWith("-") ? cmd.slice(1) : cmd; // login-shell "-bash"
  return SHELLS.has(base);
}

// Emit one notification: a GENERIC stdout log line (session + status only,
// never command output — the observability + test channel for the encrypted
// payload) then the real push.
function emitNotify(payload, logInfo) {
  console.log(`[push] notify ${JSON.stringify(logInfo)}`);
  void push
    .sendToAll(payload)
    .catch((err) => console.warn(`[push] sendToAll failed: ${err.message}`));
}

function finishBody(name, durationMs) {
  const dur = durationMs == null ? "" : ` in ${Math.round(durationMs / 1000)}s`;
  return `${name}: finished${dur}.`;
}

// Title reflects success/failure when the exit code is known (bash/zsh); stays
// neutral otherwise. GENERIC — session-level status only, never command output.
function finishTitle(exitCode) {
  if (exitCode == null) return "Job finished";
  if (exitCode === 0) return "✓ Job finished";
  return `✗ Job failed (exit ${exitCode})`;
}

// ---------------------------------------------------------------------------
// Hook-notify: per-turn notifications from an interactive claude/codex CLI
// session, via POST /api/push/hook-notify. A SECOND, independent signal source
// feeding the SAME sink (emitNotify/push.sendToAll) as the shell-transition
// poll loop above — nothing about VAPID, the subscription store, or the SW
// changes. See docs/HOOK-NOTIFICATIONS-SETUP.md for the full design record.
// ---------------------------------------------------------------------------

// Resolve a hook's session reference (bare tmux name OR qualified
// "<serverId>/<tmuxName>") to exactly one LIVE qualified session id.
//
// Reviewer note (Codex): a bare-name match against metadata alone is NOT
// authoritative — dead-session metadata persists indefinitely (see
// listSessions() above), so a stale/deleted session's name would still
// resolve. This confirms liveness with one targeted `tmux has-session`
// (sessionExists(), already used elsewhere) per candidate — cheap (normally
// exactly one candidate, one exec, possibly over SSH) and fails CLOSED on
// zero or more-than-one live match rather than guessing.
async function resolveHookSession(ref) {
  if (typeof ref !== "string" || !ref)
    return { qid: null, reason: "unknown_session" };
  const meta = metadata.list();
  const candidates = [];
  if (ref.includes("/")) {
    if (meta[ref]) candidates.push(ref);
  } else {
    for (const qid of Object.keys(meta)) {
      if (parseSessionRef(qid).tmuxName === ref) candidates.push(qid);
    }
  }
  if (candidates.length === 0) return { qid: null, reason: "unknown_session" };

  const servers = registry.list();
  const serverById = new Map(servers.map((s) => [s.id, s]));
  const alive = [];
  await Promise.all(
    candidates.map(async (qid) => {
      const { serverId, tmuxName } = parseSessionRef(qid);
      const server = serverById.get(serverId);
      if (!server) return;
      if (await sessionExists(server, tmuxName)) alive.push(qid);
    }),
  );
  if (alive.length === 0) return { qid: null, reason: "unknown_session" };
  if (alive.length > 1) return { qid: null, reason: "ambiguous_session" };
  return { qid: alive[0], reason: null };
}

// Idempotency: collapse repeated hook calls for the SAME (session, tool, kind,
// eventId) — a Claude/Codex hook can legitimately retry or double-fire. Keyed
// on the caller-supplied eventId (turn/prompt id) when present; falls back to
// a short same-kind cooldown when absent (older CLI versions with no id).
// Bounded + swept so a long-running gateway never accumulates unbounded state.
const HOOK_DEDUP_TTL_MS = 10 * 60 * 1000; // 10 min
const HOOK_DEDUP_MAX_ENTRIES = 2000;
const hookDedup = new Map(); // key -> expiresAt

function hookDedupSweep(now) {
  if (hookDedup.size <= HOOK_DEDUP_MAX_ENTRIES) return;
  for (const [key, expiresAt] of hookDedup) {
    if (expiresAt <= now) hookDedup.delete(key);
  }
}

function hookIsDuplicate(qid, tool, kind, eventId) {
  const now = Date.now();
  hookDedupSweep(now);
  const key = eventId
    ? `id:${qid}:${tool}:${kind}:${eventId}`
    : `cooldown:${qid}:${tool}:${kind}`;
  const expiresAt = hookDedup.get(key);
  if (expiresAt && expiresAt > now) return true;
  hookDedup.set(key, now + (eventId ? HOOK_DEDUP_TTL_MS : 2000));
  return false;
}

// Global abuse guard, independent of the idempotency cache above (a buggy or
// malicious hook firing in a tight loop must not exhaust push-service quota).
// Simple fixed-window counter per session.
const HOOK_RATE_LIMIT_WINDOW_MS = 60_000;
const HOOK_RATE_LIMIT_MAX = 20; // per session per minute
const hookRateLimit = new Map(); // qid -> { count, windowStart }

function hookRateLimited(qid) {
  const now = Date.now();
  const rec = hookRateLimit.get(qid);
  if (!rec || now - rec.windowStart >= HOOK_RATE_LIMIT_WINDOW_MS) {
    hookRateLimit.set(qid, { count: 1, windowStart: now });
    return false;
  }
  rec.count++;
  return rec.count > HOOK_RATE_LIMIT_MAX;
}

// FIXED template copy only — a caller-supplied `detail` is never echoed into
// the push title/body (it is logged only, capped, enum-like). This is the
// mitigation for the Codex `notify` argv finding: since Codex's legacy
// `notify` payload can carry real prompt/response text, the gateway must never
// relay ANY caller-supplied text into the encrypted push payload.
// `meta` is the session's metadata record (name/org/project — the SAME
// user-assigned labels already shown in the sidebar, never CLI content), used
// only to tell notifications for different sessions apart. Title stays
// generic (mirrors finishTitle's shell-job pattern); the session identity
// goes in the body.
function hookNotifyCopy(tool, kind, meta) {
  const label = tool === "codex" ? "Codex" : "Claude";
  const name = meta && meta.name ? meta.name : null;
  const scope =
    meta && (meta.org || meta.project)
      ? ` (${[meta.org, meta.project].filter(Boolean).join("/")})`
      : "";
  const suffix = name ? ` — ${name}${scope}` : "";
  if (kind === "waiting-input") {
    return {
      title: `${label} needs input`,
      body: `A permission prompt is waiting${suffix}.`,
    };
  }
  return {
    title: `${label} finished`,
    body: `${label} finished responding${suffix}.`,
  };
}

async function pushPollTick() {
  if (!push.isConfigured() || push.count() === 0) return;
  const settings = push.getSettings();
  let sessions;
  try {
    sessions = await listSessions();
  } catch (err) {
    console.warn(`[push] poll list failed: ${err.message}`);
    return;
  }
  const now = Date.now();
  const finished = []; // { s, durationMs }
  const running = []; // sessions crossing the still-running threshold
  const seen = new Set();

  for (const s of sessions) {
    // Only reachable rows carry a real currentCommand. Unreachable rows return
    // a fabricated "" — letting that overwrite state would fire spurious pushes
    // on flap (job -> "" -> job). Skip them entirely => a flap is a no-op.
    if (!s.reachable) continue;
    if (s.alive === false) continue; // Dead session: no tmux, no job to track.
    seen.add(s.id);
    const curr = s.currentCommand || "";
    const currShell = isShellCommand(curr);
    const prev = pushState.get(s.id);

    // Baseline / first sighting: seed only, notify nothing. A job already
    // running here started before we could time it => startedAt unknown.
    if (pushBaselinePending || prev === undefined) {
      pushState.set(s.id, {
        cmd: curr,
        startedAt: null,
        notifiedRunning: false,
      });
      continue;
    }

    const prevShell = isShellCommand(prev.cmd);
    if (prevShell && !currShell) {
      // shell -> non-shell: a job STARTED. Time it.
      pushState.set(s.id, {
        cmd: curr,
        startedAt: now,
        notifiedRunning: false,
      });
    } else if (!prevShell && currShell) {
      // non-shell -> shell: a job FINISHED.
      const durationMs = prev.startedAt != null ? now - prev.startedAt : null;
      // Duration gate: suppress jobs shorter than the threshold. A job whose
      // start we never timed (startedAt null; e.g. running since baseline) is
      // long by construction => notify with unknown duration.
      const longEnough =
        durationMs == null || durationMs >= settings.minDurationMs;
      if (!s.muted && longEnough) finished.push({ s, durationMs });
      pushState.set(s.id, {
        cmd: curr,
        startedAt: null,
        notifiedRunning: false,
      });
    } else {
      // No shell transition. Keep timing/notified state; refresh cmd.
      pushState.set(s.id, {
        cmd: curr,
        startedAt: prev.startedAt,
        notifiedRunning: prev.notifiedRunning,
      });
      // "Still running after threshold" (opt-in): fire ONCE when a timed job
      // crosses minDurationMs while still non-shell.
      if (
        settings.notifyOnStart &&
        !currShell &&
        !s.muted &&
        prev.startedAt != null &&
        !prev.notifiedRunning &&
        now - prev.startedAt >= settings.minDurationMs
      ) {
        running.push(s);
        pushState.get(s.id).notifiedRunning = true;
      }
    }
  }
  // Forget sessions that vanished so a re-created id re-baselines cleanly.
  for (const id of [...pushState.keys()]) {
    if (!seen.has(id)) pushState.delete(id);
  }
  pushBaselinePending = false;

  for (const { s, durationMs } of finished) {
    const exitCode = typeof s.exitCode === "number" ? s.exitCode : null;
    const payload = {
      title: finishTitle(exitCode),
      body: finishBody(s.name, durationMs),
      sessionId: s.id,
      tag: `job-${s.id}`,
      ...(durationMs != null ? { durationMs } : {}),
      ...(exitCode != null ? { exitCode } : {}),
    };
    emitNotify(payload, {
      sessionId: s.id,
      kind: "finish",
      durationMs: durationMs ?? null,
      exitCode,
    });
    // Consume the exit code so a stale value can never re-fire (best-effort).
    if (exitCode != null) {
      const { serverId, tmuxName } = parseSessionRef(s.id);
      const srv = registry.get(serverId);
      if (srv) {
        void serverExec(srv, [
          "set-option",
          "-t",
          tmuxName,
          "-q",
          "@web_last_exit",
          "",
        ]).catch(() => {});
      }
    }
  }
  for (const s of running) {
    const payload = {
      title: "Job still running",
      body: `${s.name}: still running.`,
      sessionId: s.id,
      tag: `running-${s.id}`,
      running: true,
    };
    emitNotify(payload, { sessionId: s.id, kind: "running", durationMs: null });
  }
}

// Start the loop (idempotent). Resets baseline state so stopped->running always
// re-baselines; a 2nd subscription while already running is a no-op (no
// re-baseline). Called on subscribe and at boot when subscriptions persist.
function startPushLoop() {
  if (pushPollTimer) return;
  if (!push.isConfigured() || push.count() === 0) return;
  pushState = new Map();
  pushBaselinePending = true;
  pushPollTimer = setInterval(() => void pushPollTick(), PUSH_POLL_INTERVAL_MS);
  if (pushPollTimer.unref) pushPollTimer.unref();
  console.log("[push] job-finished poll loop started");
}

// Stop the loop and clear state so a future start re-baselines from scratch.
function stopPushLoop() {
  if (!pushPollTimer) return;
  clearInterval(pushPollTimer);
  pushPollTimer = null;
  pushState = new Map();
  pushBaselinePending = true;
  console.log("[push] job-finished poll loop stopped");
}

